package com.duckmoim.chat.domain;

/**
 * 채팅 이미지의 상태 (CH-14 · CH-17).
 *
 * <p><b>셋인 이유는 고아가 두 종류이기 때문이다.</b> 「올리고 확정 안 함」과 「확정했는데 전송 안 함」은 사용자에게 같은 일(사진을 고르다 말았다)이지만, 서버가
 * 아는 것이 다르다 — 앞쪽은 S3 에 객체가 있는지조차 모른다.
 *
 * <pre>
 * PENDING ──확정──▶ CONFIRMED ──전송──▶ ATTACHED
 *    │                  │                  │
 *    └── 배치가 지운다 ──┘            지우지 않는다
 * </pre>
 *
 * <p><b>되돌아가는 전이가 없다.</b> 메시지를 지워도(CH-12) 이미지는 {@code ATTACHED} 로 남는다 — 소프트 삭제라 본문이 남고, 신고(CH-21)와
 * 관리자 열람(AD-08)이 판단 재료를 갖는 것과 같은 이유다.
 */
public enum ChatImageStatus {

  /** 서명을 발급했다. 올라왔는지 모른다. */
  PENDING,

  /** 저장소에 올라온 것을 확인했다. 실제 형식·크기를 보았다. */
  CONFIRMED,

  /** 메시지에 실렸다. 배치가 건드리지 않는다. */
  ATTACHED
}
