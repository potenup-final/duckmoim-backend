package com.duckmoim.chat.domain;

/**
 * 채팅 이미지의 상태 (CH-14 · CH-17).
 *
 * <p><b>셋인 이유는 고아가 두 종류이기 때문이다.</b> 「올리고 확정 안 함」과 「확정했는데 전송 안 함」은 사용자에게 같은 일(사진을 고르다 말았다)이지만, 서버가
 * 아는 것이 다르다 — 앞쪽은 S3 에 객체가 있는지조차 모른다.
 *
 * <pre>
 * PENDING ──확정──▶ CONFIRMED ──전송──▶ ATTACHED   (지우지 않는다)
 *    │                  │
 *    └──── 배치가 집는다 ─┴──▶ DELETING ──S3 삭제──▶ 행 삭제
 * </pre>
 *
 * <p><b>{@code DELETING} 은 「배치가 먼저 못박았다」는 표시다</b> (PR #147 리뷰). S3 삭제는 롤백이 안 되므로, 객체를 지우기 <b>전에</b>
 * 이 행이 배치의 것이라는 사실이 커밋돼 있어야 한다. 처음에는 한 트랜잭션 안에서 읽고 → S3 를 지우고 → 행을 지웠는데, 그 사이에 전송이 사진을 붙이고 커밋하면
 * <b>이미 붙은 사진의 객체가 지워졌다.</b>
 *
 * <pre>
 * 배치  SELECT  7 (CONFIRMED)
 * 전송            attach → ATTACHED → COMMIT
 * 배치  S3 삭제 ✗   ← 되돌릴 수 없다
 * 배치  행 삭제
 * </pre>
 *
 * <p><b>메시지를 지우거나 가려도 사진은 {@code ATTACHED} 로 남고 S3 객체도 지우지 않는다</b> (PR #147 리뷰). 「고아인데 왜 안 지우지」로 읽힐
 * 수 있어 적어 둔다 — 소프트 삭제라 본문이 남는 이유(신고 CH-21 · 관리자 열람 AD-08 의 판단 재료)가 사진에도 그대로 적용된다. <b>사용자에게는 이미 안
 * 나간다</b> — 조회 조립이 {@code status != ACTIVE} 면 {@code imageId} 를 끊는다. 실제로 지우는 것은 보관 기간이 끝난 뒤의
 * 파기(CH-19)다.
 */
public enum ChatImageStatus {

  /** 서명을 발급했다. 올라왔는지 모른다. */
  PENDING,

  /** 저장소에 올라온 것을 확인했다. 실제 형식·크기를 보았다. */
  CONFIRMED,

  /** 메시지에 실렸다. 배치가 건드리지 않는다. */
  ATTACHED,

  /**
   * 배치가 지우기로 못박았다. 이 상태가 커밋된 뒤에야 S3 객체를 지운다.
   *
   * <p>확정도 전송도 이 상태를 받지 않는다 — 이미 24시간을 넘긴 고아라 사용자에게는 「업로드된 이미지를 찾을 수 없다」가 맞는 답이다.
   *
   * <p><b>S3 삭제가 실패하면 이 상태로 남는다.</b> 다음 주기가 다시 집어 지운다 — 행을 지우면 객체 키를 되찾을 길이 없어서다.
   */
  DELETING
}
