package com.duckmoim.safety.domain;

/**
 * 제재 종류 (AD-04 · 도메인-모델링.md 「6. 라이프사이클」의 제재 축).
 *
 * <p><b>{@code NONE} 이 여기 없다.</b> 도메인 6장의 상태 축에는 다섯이 적혀 있지만, {@code NONE} 은 「제재가 없다」는 상태이지 걸 수 있는
 * 제재가 아니다. API-설계.md 2-7 이 해제를 {@code DELETE} 로 정하면서 <i>"{@code NONE} 은 그중 무엇도 아닌 「제재가 없다」 는 상태다.
 * 남길 기록이 없으니 생성이 아니라 삭제다"</i> 라고 적은 것과 같은 이유다 — 이 표에 행이 없는 것이 곧 {@code NONE} 이다.
 *
 * <p><b>종류마다 막는 것이 다르다.</b> 「제재 = 차단」으로 뭉뚱그리면 {@code WARNED} 행이 깨진다. 판정은 {@link SanctionPolicy} 가 한
 * 곳에서 한다.
 */
public enum SanctionKind {

  /**
   * 경고. <b>쓰기를 막지 않는다</b> (도메인 6장 · 화면 계약 「제재 상태」).
   *
   * <p>화면에 배너만 뜬다. 도메인 6장이 <i>"막을 것이면 정지를 준다"</i> 고 적었다. 해소는 조치일로부터 1년이다.
   */
  WARNED,

  /**
   * 나이 확인 보류. <b>벌이 아니라 확인 절차다</b> (도메인 6장).
   *
   * <p>만 14세 미만이라는 구체적인 신고가 들어와 본인에게 확인을 요청했는데 답이 없을 때 건다. 개인정보 처리방침 제10조가 「답이 없으면 먼저 글쓰기를 제한하고, 읽는
   * 것은 그때까지 제한하지 않는다」고 이미 공개한 절차다.
   *
   * <p><b>사용자에게 보이는 문구에서 「제재」라는 말을 쓰지 않는다.</b>
   */
  AGE_HOLD,

  /** 기간 정지. 쓰기가 막히고 {@code until} 이 지나면 스스로 풀린다. */
  SUSPENDED,

  /**
   * 영구 정지. 쓰기가 막힌다.
   *
   * <p>해소가 없다. 관리자가 푸는 것 말고는 돌아올 길이 없다.
   *
   * <p><b>읽기 차단은 아직 없다.</b> 도메인 6장 제재 축 표는 이 종류가 읽기도 막는다고 적었지만, 제재를 읽는 자리가 쓰기 관문({@code
   * SanctionGateInterceptor})과 {@code /users/me} 안내 둘뿐이고 로그인 경로에는 없다. <b>지금 이 값은 기한 없는 {@code
   * SUSPENDED} 와 동작이 같다</b> — 걸어도 계속 둘러본다. 그러니 「읽기까지 막았다」고 믿고 걸면 안 된다.
   *
   * <p>붙일 자리는 {@code AuthService.lockUser} 가 탈퇴 계정을 「없는 회원」으로 접는 그 줄 옆이다. 다만 거기서 막으면 당사자가 AU-12 의
   * 제재 안내를 영영 못 보므로 (로그인 자체가 401 이 된다) 그 판단이 함께 필요하다. <b>별도 티켓이다.</b>
   */
  BANNED;

  /**
   * 이 제재가 쓰기를 막는가 (I-14).
   *
   * <p>도메인 6장 제재 축 표의 「쓰기」 열 그대로다. {@code WARNED} 만 가능이다.
   */
  public boolean blocksWriting() {
    return this != WARNED;
  }

  /** 기간이 정해진 제재인가. {@code until} 을 갖는 것은 이것뿐이다 (화면 계약). */
  public boolean hasUntil() {
    return this == SUSPENDED;
  }
}
