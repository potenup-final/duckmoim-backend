package com.duckmoim.safety.domain;

/**
 * 신고를 무엇으로 종결했는가 (AD-03).
 *
 * <p><b>도메인-모델링.md 5장이 미결로 남긴 자리다.</b> <i>"상태는 정해졌지만 「무엇으로 종결했는가」를 자유 문자열로 둘지 enum 으로 둘지는 미정이다.
 * 구현하면서 정하기로 했다."</i> STAR-78 이 <b>enum 과 자유 메모 둘로</b> 정했다.
 *
 * <p>자유 문자열 하나로 두면 그 문서가 지적한 대로 「제재 없이 종결한 신고가 몇 건인가」를 셀 수 없고 관리자마다 다른 문구를 적는다. 반대로 이 값 하나만 두면 관리자가
 * 판단 맥락을 남길 자리가 없어진다. 그래서 세는 축은 여기가 지고, 문장은 {@code memo} 가 진다.
 *
 * <p><b>값을 새로 지어내지 않았다.</b> 신고 처리의 조치 경로가 AD-04(제재)와 AD-07(블라인드) 둘이므로 종결 사유도 그 축이다. 조치를 안 한 것까지
 * 셋이다.
 *
 * <p><b>제재와 블라인드를 함께 한 경우는 {@link #USER_SANCTIONED} 다.</b> 둘을 다 표현하려면 값이 아니라 집합이 되어야 하는데, 그러면 세는 축이
 * 흐려진다. 무거운 쪽을 남긴다 — 댓글은 가려지면 끝이지만 제재는 계정에 남는다.
 */
public enum ReportResult {

  /** 조치하지 않고 종결했다. 신고 사유가 확인되지 않았거나 문제가 아니었다. */
  NO_ACTION,

  /** 댓글을 가렸다 (AD-07). */
  COMMENT_BLINDED,

  /** 유저를 제재했다 (AD-04). */
  USER_SANCTIONED
}
