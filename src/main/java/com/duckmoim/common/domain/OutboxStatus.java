package com.duckmoim.common.domain;

/**
 * 아웃박스 행의 발송 상태.
 *
 * <p><b>실패가 값으로 없다.</b> 발송이 실패한 행은 {@link #PENDING} 으로 남고 시도 횟수와 다음 시도 시각만 밀린다 (NT-03) — 실패는 「아직 못
 * 보냈다」의 한 형태라 상태가 갈리지 않는다. 세 번 실패한 건은 DLQ 표로 옮기고 이 표에서 지우므로, 그 상태도 여기 없다.
 *
 * <p>도메인 문서의 상태 머신 목록에는 아웃박스가 없다. 거기 있는 것은 알림함의 {@code Notification}(안 읽음 → 읽음 → 파기)이고 이 표와 다른 것이다.
 */
public enum OutboxStatus {

  /** 아직 보내지 못했다. 한 번도 시도하지 않은 것과 실패해서 기다리는 것이 모두 여기다. */
  PENDING,

  /** 알림함에 알림을 만들었다 (NT-02). 종착이다. */
  SENT
}
