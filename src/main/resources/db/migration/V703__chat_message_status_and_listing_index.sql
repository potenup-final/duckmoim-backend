-- 메시지 삭제(CH-12)와 목록 조회(CH-09).
--
-- V702 가 둘 다 미뤄 두고 이 티켓 앞으로 메모를 남겼다 — 상태 컬럼은 「CH-12 · AD-09 몫」,
-- 인덱스는 「CH-09 가 커서를 정한 뒤에 그 정렬 키로 건다」 였다.

-- 소프트 삭제 (CH-12).
--
-- **시각 컬럼이 아니라 상태다.** comment.status 와 같은 배치이고 근거도 같다 — 지운 메시지는
-- 사라지는 것이 아니라 자리표시자로 남아야 해서 어차피 상태가 필요하다. V801(알림 읽음)이
-- 반대로 read_at DATETIME 을 고른 것과 갈리는 이유는 그쪽의 실제 상태가 둘뿐이었기
-- 때문이다. 여기는 AD-09(메시지 블라인드)가 셋째 상태로 예정돼 있다.
--
-- BLINDED 를 지금 만들지 않는다. 쓰지 않는 값이 남으면 그것이 다음 담당의 기준선이 된다.
--
-- DEFAULT 를 남긴다. 이 표는 V702 로 막 생겨 운영에 아직 없지만, 기본값 없이 NOT NULL 을
-- 더하면 행이 있는 환경(개발자 PC)에서 ALTER 자체가 실패한다.
ALTER TABLE chat_message
    ADD COLUMN status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE';

-- 목록 조회 (CH-09).
--
-- 질의는 「한 방의 메시지를 최신부터 거슬러」다.
--
--   WHERE room_id = ? AND id < ?  ORDER BY id DESC  LIMIT ?
--
-- **정렬 키가 id 하나다.** 다른 목록들이 (정렬키, id) 두 값인 것은 정렬키만으로 동점이
-- 생겨서인데(V804 의 알림함이 그 경우다), id 는 그 자체로 삽입 순서의 전순서라 덧댈 것이
-- 없다. 커서도 같은 이유로 한 값이다.
--
-- **인덱스 · 커서 · ORDER BY 셋의 키가 같아야 한다.** 하나라도 어긋나면 페이지 경계에서
-- 누락이 생기고, 그 증상은 「가끔 한 줄이 안 보인다」라 재현이 어렵다.
--
-- DESC 를 붙이지 않는다. B-tree 는 양방향으로 읽을 수 있어 (room_id, id) 하나로 최신순과
-- 오래된 순을 모두 덮는다. 방향을 박으면 반대로 읽는 질의가 생길 때 인덱스가 하나 더 는다.
--
-- status 를 키에 넣지 않는다. 지운 메시지도 자리표시자로 목록에 남으므로(CH-12) 질의가
-- 그 컬럼으로 거르지 않는다.
CREATE INDEX idx_chat_message_listing ON chat_message (room_id, id);
