-- 계정 파기 (AD-05). Identity 새 대역(V200~V299)의 첫 파일이다.
-- 두 자리 대역(V10~V14)은 2026-09-10 에 동결됐다 (DB-마이그레이션-규칙 「버전 대역」).
--
-- 명세: 「감사 로그가 남기는 행위 다섯 — 제재 · 해제 · 비밀 댓글 열람 · 블라인드 · 계정 파기」.
-- 넷은 쌓이는데 파기만 비어 있었다. enum 의 PURGE 를 부르는 쪽이 없어서다.
--
-- **둘 다 넓히는 변경이다.** NOT NULL → NULL 과 ADD COLUMN NULL 이라, 무중단 배포의 전환
-- 구간에 아직 돌고 있는 구버전 코드가 그대로 돈다 (무중단배포-BlueGreen-구축보고 5-4).

-- 파기가 카카오 회원번호를 비운다. 그래서 NOT NULL 을 풀어야 한다.
--
-- **회원번호가 개인정보라서 비운다.** 탈퇴(AU-11)는 닉네임과 프로필 이미지까지만 비우고
-- 「파기 범위는 처리방침이 정할 일」이라며 나머지를 남겨 두었는데, 이 티켓이 그 범위를 정했다.
--
-- **uk_user_kakao_user_id 는 그대로 둔다.** MySQL 유니크는 NULL 중복을 허용해서, 파기된
-- 계정이 여럿이어도 제약이 깨지지 않는다. uk_user_nickname 이 탈퇴에 대해 이미 같은 자리를
-- 잡았다 — User.withdraw 가 닉네임을 고정 문자열이 아니라 NULL 로 만드는 이유가 그것이다.
--
-- **비우면 같은 카카오 계정이 새 계정으로 다시 들어온다.** 조회가 회원번호로 거는데 NULL 은
-- 어디에도 안 걸리기 때문이다. 탈퇴가 닉네임을 풀어 남이 가져갈 수 있게 한 것과 같은 결이고,
-- 파기의 뜻이 「이 사람의 흔적을 지운다」이지 「이 사람을 영구히 막는다」가 아니라서 맞다.
-- 영구 차단은 제재(BANNED)의 일이다.
ALTER TABLE user
    MODIFY COLUMN kakao_user_id BIGINT NULL;

-- 이 계정을 파기한 시각. 아직 파기하지 않은 계정은 NULL 이다.
--
-- **행을 지우지 않아서 이 열이 필요하다.** 작성자 블록이 user 행을 내부 조인으로 읽으므로
-- (API 2-5) 행을 지우면 그 사람의 댓글·모집글이 목록에서 통째로 빠진다. 탈퇴가 소프트
-- 삭제인 이유와 같다.
--
-- **status 로 대신할 수 없다.** 파기하면 WITHDRAWN 이 되는데 그냥 탈퇴한 사람도 WITHDRAWN
-- 이라, 이 열이 없으면 둘을 구별할 수 없다. 두 번째 파기를 409 로 막는 판정도 이 열이 진다.
--
-- **비워진 컬럼으로 판정하지 않는다.** 「kakao_user_id 가 NULL 이면 파기된 것」으로 읽으면
-- 파기 범위가 바뀌는 날 판정이 함께 깨진다. 사실을 적는 열을 따로 둔다.
--
-- chat_room.purged_at 이 같은 이름을 쓴다 (V707 · CH-19). 같은 뜻이면 같은 이름으로 둔다.
ALTER TABLE user
    ADD COLUMN purged_at DATETIME(6) NULL;

-- 인덱스를 두지 않는다.
--
-- 파기는 관리자가 회원 하나를 지목해 부르는 단건 경로다 (API 2-7). PK 로 한 행을 읽은 뒤에
-- 걸리는 조건이라 인덱스가 할 일이 없다. 파기된 계정을 훑는 목록 요구사항도 아직 없다.
