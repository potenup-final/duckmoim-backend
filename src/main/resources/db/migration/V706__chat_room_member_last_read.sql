-- 멤버별 마지막 읽은 지점 (CH-13). Chat 대역(V700~V799)의 일곱째 파일이다.
--
-- V700 이 이 티켓 앞으로 남긴 자리다 —
--   「멤버별 마지막 읽은 지점」 컬럼이 아직 없다. 타입이 CH-09 의 커서 정의에 달려 있고
--   그것이 아직 없다. CH-13(안 읽은 수) 티켓이 더한다.
--
-- 그 커서를 CH-09(STAR-112)가 messageId 하나로 정했다. (createdAt, id) 두 값이었으면
-- 여기가 DATETIME + BIGINT 두 칸이 됐다.
--
-- **방이 아니라 멤버 행에 둔다** (도메인 3.1 「읽은 지점은 멤버 행에만 쓴다」). 방 행에
-- 두면 여럿이 동시에 읽기만 해도 서로 기다린다 — CH-13 의 검증 기준 둘째 줄이
-- 「갱신이 방 행을 잠그지 않는다」인 이유다. 성능이 아니라 설계 제약이다.
--
-- NULL 은 「한 번도 읽지 않았다」다. 0 을 기본값으로 두지 않는 것은, 0 이 유효한 messageId
-- 가 아닌 것에 기대는 값이라 나중에 커서 모양이 바뀌면 조용히 틀리기 때문이다.
--
-- FK 를 걸지 않는다. chat_message 와는 애그리게이트가 다르고 (Message 는 ChatRoom 밖이다),
-- 가리키던 메시지가 CH-19 의 파기로 사라져도 이 값은 그대로여도 된다 — 세는 질의가
-- 「이 번호보다 큰 것」을 세지, 그 번호의 행을 찾지 않는다.
ALTER TABLE chat_room_member
    ADD COLUMN last_read_message_id BIGINT NULL;

