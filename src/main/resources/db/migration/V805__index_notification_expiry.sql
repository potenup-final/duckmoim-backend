-- Notification 대역(V800~V899). V804 까지 썼으므로 V805 다.
--
-- 알림 만료 배치의 인덱스다 (NT-11a). 배치가 도는 질의는 하나다 —
-- `WHERE created_at < ? ORDER BY created_at LIMIT ?`.
--
-- **탈 인덱스가 없었다.** 이 표의 인덱스 셋은 선두 컬럼이 각각 id(PK) · outbox_id · recipient_id
-- 라 created_at 하나로 거르는 이 질의는 셋 다 못 타고 풀 스캔이 된다. V804 가 목록 조회를 위해
-- (recipient_id, created_at, id) 를 깔았지만 선두가 recipient_id 라 여기서는 쓸모가 없다.
--
-- **정렬 키와 같은 컬럼이라 LIMIT 이 싸게 끝난다.** 인덱스를 앞에서부터 읽다가 청크만큼에서
-- 멈춘다. 정렬을 인덱스로 못 풀면 매 주기마다 만료 대상 전부를 정렬한 뒤 앞부분만 쓰게 된다.
--
-- **잠금 표(shedlock)를 만드는 대신 여기 쓴다.** 배치가 둘이 도는 것을 막지 않기로 했고
-- (ADR 0009) 삭제가 멱등이라 막을 것이 없다. 두 인스턴스가 이 인덱스를 같은 순서로 읽어
-- 락 획득 순서가 같아지는 것이 데드락이 안 나는 근거이기도 하다.
--
-- id 를 뒤에 붙이지 않았다. V804 에서는 커서 페이지네이션이라 동점을 가르는 것이 정확성
-- 문제였는데, 여기는 지우고 나면 다음 주기에 그 행이 없어서 경계가 어긋날 자리가 없다.
CREATE INDEX idx_notification_expiry
    ON notification (created_at);
