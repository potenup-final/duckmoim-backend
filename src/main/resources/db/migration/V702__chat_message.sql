-- 메시지 (CH-07). Chat 대역(V700~V799)의 셋째 파일이다.
--
-- Message 는 ChatRoom 밖의 애그리게이트다 (도메인-모델링.md 「3.1 경계와 트랜잭션 범위」).
-- 「메시지 규칙 중 방을 바꿔야 하는 것이 없다」가 근거이고, 그래서 전송이 chat_room 행을
-- 건드리지 않는다 — 여럿이 동시에 보내도 서로 기다리지 않는다.
CREATE TABLE chat_message
(
    id                BIGINT        NOT NULL AUTO_INCREMENT,

    -- 애그리게이트 밖은 ID 로만 참조한다 (도메인 3.2). FK 를 걸지 않는다.
    room_id           BIGINT        NOT NULL,

    -- 보낸 사람.
    --
    -- 유비쿼터스 언어에 항목이 없어 여기서 정했다 (도메인 3.1 의 경계 안 목록은 「작성자」).
    -- comment.author_id 를 따르지 않은 것은 메시지를 「쓴다」보다 「보낸다」고 말하기
    -- 때문이고, 응답 필드도 senderId 로 나간다. 위키 반영은 별도 클론에서 따라온다.
    sender_id         BIGINT        NOT NULL,

    -- 클라이언트가 만든 식별자 (CH-07 · I-20).
    --
    -- **이 컬럼이 있는 이유는 재시도다.** 전송 응답을 못 받은 클라이언트가 같은 메시지를
    -- 다시 보내는데, 서버가 만든 번호로는 그 둘이 같은 것인지 알 수 없다.
    --
    -- 64자인 것은 UUID(36자)에 여유를 둔 값이다. 형식을 강제하지 않는다 — 우리가 만든 값이
    -- 아니라 검증할 근거가 없고, 뒤의 유니크 제약이 형식과 무관하게 성립한다.
    client_message_id VARCHAR(64)   NOT NULL,

    -- 최대 1000자 (CH-07).
    --
    -- 도메인에서 다시 세지 않는다. comment.content 가 VARCHAR(500) 으로 정한 자리와 같다 —
    -- 「같은 숫자를 세 곳에 두면 한 곳만 고치는 날이 온다」. 요청 DTO 의 @Size 와 이 컬럼
    -- 둘을 지나지 않는 경로가 없다.
    content           VARCHAR(1000) NOT NULL,

    created_at        DATETIME(6)   NOT NULL,
    updated_at        DATETIME(6)   NOT NULL,

    PRIMARY KEY (id),

    -- I-20 의 이중 방어다. 도메인-모델링.md 5장이 「유니크 제약 → 기존 건 반환」으로 정했다.
    --
    -- **범위를 보낸 사람으로 좁힌 것이 이 파일의 판단이다.** 불변식은 「같은 클라이언트
    -- 식별자로 온 메시지는 한 건만 저장된다」 라고만 적고 범위를 말하지 않는데, 식별자만으로
    -- 걸면 「기존 건 반환」이 **남의 메시지 본문을 돌려주는 경로**가 된다 — 식별자를 만드는
    -- 쪽이 클라이언트이고 우리가 그 값을 검증하지 않기 때문이다. 보낸 사람으로 좁히면
    -- 돌려주는 행이 항상 호출자 자신의 것이라 그 경로가 구조적으로 닫힌다.
    --
    -- 방 번호를 넣지 않은 것은 불변식을 글자 그대로 읽은 결과다. 한 사람이 같은 식별자를
    -- 두 방에 쓰면 두 건이 되는데, 그러면 「한 건만 저장된다」가 깨진다.
    CONSTRAINT uq_chat_message_sender_client_id UNIQUE (sender_id, client_message_id)

    -- 목록 조회 인덱스를 두지 않았다. 그 질의는 「한 방의 메시지를 최신부터 거슬러」(CH-09)
    -- 이고 커서의 정렬 키가 아직 없다 — V801 이 알림함 인덱스를 같은 이유로 미뤘다.
    -- STAR-112 가 커서를 정하면서 그 키로 건다.
) DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_0900_ai_ci;

-- 삭제·블라인드 컬럼이 없다. CH-12(작성자 삭제)와 AD-09(관리자 블라인드)가 각각의 티켓이고,
-- V700 이 「읽은 지점」을 CH-13 에 넘긴 것과 같은 자리다. 미리 만들면 쓰지 않는 컬럼이
-- 남고 그 컬럼이 다음 담당의 기준선이 된다.
--
-- 이미지 참조도 없다 (CH-14 · STAR-115).
