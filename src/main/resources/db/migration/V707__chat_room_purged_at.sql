-- 대화·이미지 파기 표시 (CH-19). Chat 대역(V700~V799)의 여덟째 파일이다.
-- V706 은 리뷰 중인 CH-13 · CH-18 (PR #155)이 쓴다.
--
-- 명세: 「모집글 마감 후 90일에 대화와 이미지를 파기한다. 배치는 멱등」.

-- 이 방의 대화와 사진을 파기한 시각. 아직 파기하지 않은 방은 NULL 이다.
--
-- **방 행 자체는 지우지 않는다.** 명세가 파기 대상으로 적은 것은 「대화와 이미지」이고,
-- 방을 지우면 CH-01a 가 없앤 「방이 없는 경우」 분기가 조회 경로에 되살아난다 — 그 티켓이
-- 기존 모집글에까지 방을 만들어 준 이유가 그 분기를 두지 않기 위해서였다.
--
-- **그래서 이 열이 필요하다.** 파기가 끝난 방은 메시지도 사진도 0건이라 다시 지워도 결과가
-- 같지만(멱등), 표시가 없으면 그 방이 대상 목록에 영원히 남아 매일 다시 집힌다. 대상 집합이
-- 시간이 갈수록 자라고, 「집었는데 지운 것이 0건」인 주기가 정상이 되어 고장과 구별되지
-- 않는다.
--
-- 멱등을 두 겹으로 만드는 자리이기도 하다. 삭제 자체가 이미 멱등이고(먼저 지운 쪽이 이긴다,
-- S3 의 DeleteObject 는 없는 키에도 성공한다) 이 열이 두 번째 실행을 아예 대상에서 뺀다.
ALTER TABLE chat_room
    ADD COLUMN purged_at DATETIME(6) NULL;

-- 인덱스를 두지 않는다.
--
-- 파기 배치의 대상 조회는 companion_post 의 ix_companion_post_purge (status, closed_at) 에서
-- 출발해 uq_chat_room_post_id 로 이 표를 PK 조인한다 (V300). 그 순서에서 purged_at 은 이미
-- 한 행으로 좁혀진 뒤에 걸리는 조건이라 인덱스가 할 일이 없다.
